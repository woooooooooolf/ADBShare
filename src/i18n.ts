const stored = (() => {
  try {
    const value = JSON.parse(localStorage.getItem('adbshare.preferences') || '{}');
    return value && typeof value === 'object' ? value : {};
  } catch {
    return {};
  }
})();
export let language: Language = stored.language === 'en' ? 'en' : 'zh';
export let theme: Theme = stored.theme === 'dark' ? 'dark' : 'light';
export function t(key: Key, args: Record<string, string | number> = {}): string {
  return Object.entries(args).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    (language === 'zh' ? zh : en)[key],
  );
}
export function preferences(next: { language?: Language; theme?: Theme } = {}) {
  language = next.language || language;
  theme = next.theme || theme;
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.documentElement.dataset.theme = theme;
  if (Object.keys(next).length)
    localStorage.setItem('adbshare.preferences', JSON.stringify({ language, theme }));
}
export function translate(root: ParentNode = document) {
  root
    .querySelectorAll<HTMLElement>('[data-i18n]')
    .forEach((el) => (el.textContent = t(el.dataset.i18n as Key)));
  root
    .querySelectorAll<HTMLInputElement>('[data-placeholder]')
    .forEach((el) => (el.placeholder = t(el.dataset.placeholder as Key)));
}
